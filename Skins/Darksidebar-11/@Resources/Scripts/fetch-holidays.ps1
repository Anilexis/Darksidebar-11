# fetch-holidays.ps1
# Загрузка и кэширование официальных праздников и перенесенных выходных по стране города
param(
    [string]$CountryCode = "",
    [int]$Year = 0
)

[Console]::OutputEncoding = [System.Text.Encoding]::UTF8

$scriptsDir = $PSScriptRoot
$resourcesDir = Split-Path $scriptsDir
$settingsPath = Join-Path $resourcesDir "Settings.inc"
$cacheDir = Join-Path $resourcesDir "Cache"
$outputLua = Join-Path $cacheDir "holidays.lua"

if (-not (Test-Path $cacheDir)) {
    New-Item -ItemType Directory -Path $cacheDir -Force | Out-Null
}

if ([string]::IsNullOrWhiteSpace($CountryCode)) {
    $CountryCode = "RU"
    if (Test-Path $settingsPath) {
        $cp1251 = [System.Text.Encoding]::GetEncoding(1251)
        $lines = [System.IO.File]::ReadAllLines($settingsPath, $cp1251)
        foreach ($line in $lines) {
            if ($line -match '^\s*WeatherCountryCode\s*=\s*(.*?)\s*$') {
                if ($Matches[1]) { $CountryCode = $Matches[1].Trim().ToUpperInvariant() }
            }
        }
    }
}

if ($Year -le 0) {
    $Year = (Get-Date).Year
}

$holidays = @{}

# 1. Если Россия (RU), формируем праздники РФ (ТК РФ ст. 112) + переносы
if ($CountryCode -eq "RU") {
    $ruBase = @{
        "01-01" = "Новогодние каникулы"
        "01-02" = "Новогодние каникулы"
        "01-03" = "Новогодние каникулы"
        "01-04" = "Новогодние каникулы"
        "01-05" = "Новогодние каникулы"
        "01-06" = "Новогодние каникулы"
        "01-07" = "Рождество Христово"
        "01-08" = "Новогодние каникулы"
        "02-23" = "День защитника Отечества"
        "03-08" = "Международный женский день"
        "05-01" = "Праздник Весны и Труда"
        "05-09" = "День Победы"
        "06-12" = "День России"
        "11-04" = "День народного единства"
    }
    foreach ($k in $ruBase.Keys) {
        $dateKey = "$Year-$k"
        $holidays[$dateKey] = $ruBase[$k]
    }

    try {
        $url = "https://isdayoff.ru/api/getdata?year=" + $Year + "&country=ru"
        $wc = New-Object System.Net.WebClient
        $wc.Headers.Add("User-Agent", "Mozilla/5.0 Darksidebar-11/1.0.0")
        $raw = $wc.DownloadString($url).Trim()
        if ($raw.Length -ge 365) {
            $curDate = [DateTime]::new($Year, 1, 1)
            for ($i = 0; $i -lt $raw.Length; $i++) {
                $ch = $raw[$i]
                $k = $curDate.ToString("yyyy-MM-dd")
                $isWeekend = ($curDate.DayOfWeek -eq [DayOfWeek]::Saturday -or $curDate.DayOfWeek -eq [DayOfWeek]::Sunday)
                if ($ch -eq '1' -and (-not $isWeekend)) {
                    if (-not $holidays.ContainsKey($k)) {
                        $holidays[$k] = "Перенесенный выходной"
                    }
                }
                $curDate = $curDate.AddDays(1)
            }
        }
    } catch { }
} else {
    try {
        $url = "https://date.nager.at/api/v3/PublicHolidays/" + $Year + "/" + $CountryCode
        $wc = New-Object System.Net.WebClient
        $wc.Headers.Add("User-Agent", "Mozilla/5.0 Darksidebar-11/1.0.0")
        $wc.Encoding = [System.Text.Encoding]::UTF8
        $jsonStr = $wc.DownloadString($url)
        Add-Type -AssemblyName System.Web.Extensions
        $jss = New-Object System.Web.Script.Serialization.JavaScriptSerializer
        $arr = $jss.DeserializeObject($jsonStr)
        foreach ($item in $arr) {
            $d = $item["date"]
            $name = if ($item["name"]) { $item["name"] } else { $item["localName"] }
            if ($d -and $name) {
                $holidays[$d] = $name
            }
        }
    } catch { }
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("-- holidays.lua auto-generated by fetch-holidays.ps1")
[void]$sb.AppendLine("local M = {}")
[void]$sb.AppendLine("M.country = ""$CountryCode""")
[void]$sb.AppendLine("M.year = $Year")
[void]$sb.AppendLine("M.days = {")

foreach ($k in ($holidays.Keys | Sort-Object)) {
    $val = $holidays[$k] -replace '"', '"'
    [void]$sb.AppendLine("    [""$k""] = ""$val"",")
}

[void]$sb.AppendLine("}")
[void]$sb.AppendLine("return M")

$cp1251 = [System.Text.Encoding]::GetEncoding(1251)
[System.IO.File]::WriteAllText($outputLua, $sb.ToString(), $cp1251)
Write-Host "Holidays generated for $CountryCode ($Year): $($holidays.Count) days"
